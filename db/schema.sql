-- Repair OS — PostgreSQL schema (Postgres 13+)
CREATE EXTENSION IF NOT EXISTS "uuid-ossp";

CREATE TYPE repair_status AS ENUM (
    'lead_received','confirmed','parts_procured','in_transit',
    'in_progress','completed','cancelled','warranty_return'
);
CREATE TYPE payment_status AS ENUM ('unpaid', 'partially_paid', 'paid_in_full');
CREATE TYPE payment_type AS ENUM ('cash', 'bank_transfer', 'other');
CREATE TYPE part_category AS ENUM ('screen','battery','rear_camera','front_camera','charging_port','housing','motherboard_ic','other');
CREATE TYPE screen_quality AS ENUM ('original_pulled','oled_hard','oled_soft','incell','tft','not_applicable');

CREATE TABLE suppliers (
    id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
    name VARCHAR(150) NOT NULL,
    contact_phone VARCHAR(30),
    address_location TEXT,
    balance_credit NUMERIC(12, 2) DEFAULT 0.00, -- owed to the supplier
    notes TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE TABLE drivers (
    id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
    name VARCHAR(150) NOT NULL,
    phone VARCHAR(30) NOT NULL,
    vehicle_type VARCHAR(50) DEFAULT 'Motorcycle',
    default_rate_per_trip NUMERIC(10, 2) DEFAULT 30.00,
    wallet_balance NUMERIC(12, 2) DEFAULT 0.00, -- accrued, unpaid fees
    created_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE TABLE customers (
    id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
    full_name VARCHAR(150) NOT NULL,
    phone VARCHAR(30) UNIQUE NOT NULL,
    address_neighborhood VARCHAR(200),
    maps_pin_url TEXT,
    total_lifetime_spent NUMERIC(12, 2) DEFAULT 0.00,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE TABLE repair_tickets (
    id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
    ticket_code VARCHAR(20) UNIQUE NOT NULL, -- TFX-2026-001 (auto-generated by trigger)
    customer_id UUID REFERENCES customers(id) ON DELETE RESTRICT,

    device_brand VARCHAR(50) DEFAULT 'Apple',
    device_model VARCHAR(100) NOT NULL,
    device_color VARCHAR(50),
    device_imei_serial VARCHAR(60),
    device_passcode VARCHAR(50),

    primary_fault TEXT NOT NULL,
    part_type part_category NOT NULL,
    part_grade screen_quality DEFAULT 'not_applicable',

    status repair_status DEFAULT 'confirmed',
    scheduled_date DATE DEFAULT CURRENT_DATE,
    scheduled_time TIME,

    gross_quoted_price NUMERIC(10, 2) NOT NULL,
    deposit_amount NUMERIC(10, 2) DEFAULT 0.00,
    part_purchase_cost NUMERIC(10, 2) DEFAULT 0.00,
    supplier_id UUID REFERENCES suppliers(id) ON DELETE SET NULL,
    supplier_paid_instant BOOLEAN DEFAULT TRUE,

    driver_id UUID REFERENCES drivers(id) ON DELETE SET NULL,
    driver_fee NUMERIC(10, 2) DEFAULT 0.00,
    driver_fee_paid BOOLEAN DEFAULT FALSE,

    consumables_cost NUMERIC(10, 2) DEFAULT 10.00,

    net_profit NUMERIC(10, 2) GENERATED ALWAYS AS (
        gross_quoted_price - (part_purchase_cost + driver_fee + consumables_cost)
    ) STORED,

    payment_method payment_type DEFAULT 'cash',
    payment_state payment_status DEFAULT 'unpaid',

    audit_pre_touch BOOLEAN DEFAULT TRUE,
    audit_pre_faceid BOOLEAN DEFAULT TRUE,
    audit_pre_rear_camera BOOLEAN DEFAULT TRUE,
    audit_pre_front_camera BOOLEAN DEFAULT TRUE,
    audit_pre_microphone BOOLEAN DEFAULT TRUE,
    audit_pre_charging BOOLEAN DEFAULT TRUE,
    audit_pre_chassis_dent BOOLEAN DEFAULT FALSE,
    audit_pre_notes TEXT,

    audit_post_verified BOOLEAN DEFAULT FALSE,
    screen_protector_applied BOOLEAN DEFAULT TRUE,

    warranty_period_days INT DEFAULT 90,
    warranty_expiration_date DATE,

    completed_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ DEFAULT NOW(),

    CONSTRAINT chk_amounts_nonneg CHECK (
        gross_quoted_price >= 0 AND deposit_amount >= 0 AND part_purchase_cost >= 0
        AND driver_fee >= 0 AND consumables_cost >= 0),
    CONSTRAINT chk_deposit_le_price CHECK (deposit_amount <= gross_quoted_price)
);

CREATE TABLE driver_payouts (
    id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
    driver_id UUID REFERENCES drivers(id) ON DELETE CASCADE,
    amount_paid NUMERIC(10, 2) NOT NULL CHECK (amount_paid > 0),
    payout_date TIMESTAMPTZ DEFAULT NOW(),
    notes TEXT
);

CREATE TABLE supplier_transactions (
    id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
    supplier_id UUID REFERENCES suppliers(id) ON DELETE CASCADE,
    transaction_type VARCHAR(20) CHECK (transaction_type IN ('debt_incurred','payment_settled','rma_credit')),
    amount NUMERIC(10, 2) NOT NULL CHECK (amount > 0),
    related_ticket_id UUID REFERENCES repair_tickets(id) ON DELETE SET NULL,
    notes TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE TABLE operating_expenses (
    id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
    expense_category VARCHAR(50) NOT NULL, -- social_ads, tools, phone_4g, packaging, transport
    amount NUMERIC(10, 2) NOT NULL CHECK (amount >= 0),
    receipt_note TEXT,
    expense_date DATE DEFAULT CURRENT_DATE,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE INDEX idx_tickets_status ON repair_tickets(status);
CREATE INDEX idx_tickets_completed ON repair_tickets(completed_at);
CREATE INDEX idx_tickets_customer ON repair_tickets(customer_id);
CREATE INDEX idx_expenses_date ON operating_expenses(expense_date);

-- ===================== TRIGGERS =====================

-- Yearly ticket-code counter (race-safe)
CREATE TABLE ticket_counters (year INT PRIMARY KEY, last_seq INT NOT NULL);

-- BEFORE: code generation, economics lock, completion gating, warranty dates, payment state
CREATE FUNCTION trg_ticket_before() RETURNS trigger AS $$
DECLARE yr INT; seq INT;
BEGIN
    IF TG_OP = 'INSERT' AND (NEW.ticket_code IS NULL OR NEW.ticket_code = '') THEN
        yr := EXTRACT(YEAR FROM NOW())::INT;
        INSERT INTO ticket_counters(year, last_seq) VALUES (yr, 1)
            ON CONFLICT (year) DO UPDATE SET last_seq = ticket_counters.last_seq + 1
            RETURNING last_seq INTO seq;
        NEW.ticket_code := 'TFX-' || yr || '-' || LPAD(seq::TEXT, 3, '0');
    END IF;

    -- Unit economics are frozen once a job is completed (status changes still allowed)
    IF TG_OP = 'UPDATE' AND OLD.status IN ('completed','warranty_return') AND NEW.status IN ('completed','warranty_return') THEN
        IF (NEW.gross_quoted_price, NEW.part_purchase_cost, NEW.driver_fee, NEW.consumables_cost,
            NEW.driver_id, NEW.supplier_id, NEW.supplier_paid_instant)
           IS DISTINCT FROM
           (OLD.gross_quoted_price, OLD.part_purchase_cost, OLD.driver_fee, OLD.consumables_cost,
            OLD.driver_id, OLD.supplier_id, OLD.supplier_paid_instant) THEN
            RAISE EXCEPTION 'Economics of completed ticket % are locked', OLD.ticket_code;
        END IF;
    END IF;

    IF NEW.status = 'completed' AND (TG_OP = 'INSERT' OR OLD.status <> 'completed') THEN
        IF NOT COALESCE(NEW.audit_post_verified, FALSE) THEN
            RAISE EXCEPTION 'Cannot complete % before the post-repair verification is ticked', NEW.ticket_code;
        END IF;
        IF NEW.completed_at IS NULL THEN NEW.completed_at := NOW(); END IF;
        NEW.warranty_expiration_date :=
            (NEW.completed_at::DATE + COALESCE(NEW.warranty_period_days, 90));
    END IF;

    IF NEW.payment_state = 'paid_in_full' AND NEW.status = 'completed' THEN
        NEW.deposit_amount := NEW.gross_quoted_price;
    END IF;
    RETURN NEW;
END $$ LANGUAGE plpgsql;

CREATE TRIGGER ticket_before BEFORE INSERT OR UPDATE ON repair_tickets
    FOR EACH ROW EXECUTE FUNCTION trg_ticket_before();

-- AFTER: ledger side-effects, applied exactly once when a ticket enters/leaves 'completed'
CREATE FUNCTION trg_ticket_after() RETURNS trigger AS $$
DECLARE entering BOOLEAN; leaving BOOLEAN;
BEGIN
    entering := NEW.status = 'completed'
        AND (TG_OP = 'INSERT' OR OLD.status NOT IN ('completed','warranty_return'));
    leaving := TG_OP = 'UPDATE' AND OLD.status = 'completed'
        AND NEW.status NOT IN ('completed','warranty_return');

    IF entering THEN
        IF NEW.customer_id IS NOT NULL THEN
            UPDATE customers SET total_lifetime_spent = total_lifetime_spent + NEW.gross_quoted_price
             WHERE id = NEW.customer_id;
        END IF;
        IF NEW.driver_id IS NOT NULL AND NOT NEW.driver_fee_paid THEN
            UPDATE drivers SET wallet_balance = wallet_balance + NEW.driver_fee WHERE id = NEW.driver_id;
        END IF;
        IF NEW.supplier_id IS NOT NULL AND NOT NEW.supplier_paid_instant AND NEW.part_purchase_cost > 0 THEN
            INSERT INTO supplier_transactions(supplier_id, transaction_type, amount, related_ticket_id, notes)
            VALUES (NEW.supplier_id, 'debt_incurred', NEW.part_purchase_cost, NEW.id, 'Credit purchase ' || NEW.ticket_code);
        END IF;
    ELSIF leaving THEN
        IF NEW.customer_id IS NOT NULL THEN
            UPDATE customers SET total_lifetime_spent = GREATEST(0, total_lifetime_spent - OLD.gross_quoted_price)
             WHERE id = NEW.customer_id;
        END IF;
        IF OLD.driver_id IS NOT NULL AND NOT OLD.driver_fee_paid THEN
            UPDATE drivers SET wallet_balance = wallet_balance - OLD.driver_fee WHERE id = OLD.driver_id;
        END IF;
        IF OLD.supplier_id IS NOT NULL AND NOT OLD.supplier_paid_instant AND OLD.part_purchase_cost > 0 THEN
            INSERT INTO supplier_transactions(supplier_id, transaction_type, amount, related_ticket_id, notes)
            VALUES (OLD.supplier_id, 'rma_credit', OLD.part_purchase_cost, OLD.id, 'Ticket reopened/cancelled ' || OLD.ticket_code);
        END IF;
    END IF;
    RETURN NULL;
END $$ LANGUAGE plpgsql;

CREATE TRIGGER ticket_after AFTER INSERT OR UPDATE ON repair_tickets
    FOR EACH ROW EXECUTE FUNCTION trg_ticket_after();

-- Supplier ledger keeps suppliers.balance_credit in sync
CREATE FUNCTION trg_supplier_tx() RETURNS trigger AS $$
BEGIN
    UPDATE suppliers SET balance_credit = COALESCE(balance_credit,0) +
        CASE NEW.transaction_type WHEN 'debt_incurred' THEN NEW.amount ELSE -NEW.amount END
     WHERE id = NEW.supplier_id;
    RETURN NULL;
END $$ LANGUAGE plpgsql;
CREATE TRIGGER supplier_tx_after AFTER INSERT ON supplier_transactions
    FOR EACH ROW EXECUTE FUNCTION trg_supplier_tx();

-- Driver payout reduces wallet and flags the settled tickets as paid
CREATE FUNCTION trg_driver_payout() RETURNS trigger AS $$
BEGIN
    UPDATE drivers SET wallet_balance = COALESCE(wallet_balance,0) - NEW.amount_paid WHERE id = NEW.driver_id;
    RETURN NULL;
END $$ LANGUAGE plpgsql;
CREATE TRIGGER driver_payout_after AFTER INSERT ON driver_payouts
    FOR EACH ROW EXECUTE FUNCTION trg_driver_payout();

-- ===================== REPORTING VIEWS =====================
-- Jobs count on the day they were completed (warranty returns keep their original completion).
CREATE VIEW v_job_profit AS
SELECT t.*, (t.completed_at AT TIME ZONE 'UTC')::DATE AS job_date
  FROM repair_tickets t
 WHERE t.completed_at IS NOT NULL AND t.status IN ('completed','warranty_return');

CREATE VIEW v_daily_pnl AS
WITH j AS (
    SELECT job_date AS d, COUNT(*) AS jobs, SUM(gross_quoted_price) AS revenue,
           SUM(part_purchase_cost) AS parts, SUM(driver_fee) AS drivers,
           SUM(consumables_cost) AS consumables, SUM(net_profit) AS gross_profit
      FROM v_job_profit GROUP BY 1),
o AS (SELECT expense_date AS d, SUM(amount) AS opex FROM operating_expenses GROUP BY 1)
SELECT COALESCE(j.d, o.d) AS day,
       COALESCE(jobs,0) AS jobs, COALESCE(revenue,0) AS revenue, COALESCE(parts,0) AS parts,
       COALESCE(drivers,0) AS drivers, COALESCE(consumables,0) AS consumables,
       COALESCE(gross_profit,0) AS job_profit, COALESCE(opex,0) AS opex,
       COALESCE(gross_profit,0) - COALESCE(opex,0) AS net_margin
  FROM j FULL JOIN o ON j.d = o.d;

CREATE VIEW v_monthly_pnl AS
SELECT DATE_TRUNC('month', day)::DATE AS month, SUM(jobs)::INT AS jobs, SUM(revenue) AS revenue,
       SUM(parts) AS parts, SUM(drivers) AS drivers, SUM(consumables) AS consumables,
       SUM(job_profit) AS job_profit, SUM(opex) AS opex, SUM(net_margin) AS net_margin
  FROM v_daily_pnl GROUP BY 1;
